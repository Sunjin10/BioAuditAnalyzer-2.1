PBC_COLUMNS = [
    "기업", "규칙", "검토 신호", "관련 기준",
    "감사주장", "요청자료", "검증목적", "검증절차"
]


def build_pbc_report(risk_df):
    required = {"기업", "규칙", "검토 신호", "관련 기준"}
    missing = required - set(risk_df.columns)

    if missing:
        raise ValueError(f"필수 열 누락: {missing}")

    unknown_rules = set(risk_df["규칙"]) - set(PBC_CATALOG)

    if unknown_rules:
        raise ValueError(
            f"PBC 정보가 없는 규칙: {unknown_rules}"
        )

    results = []

    for _, risk in risk_df.iterrows():
        rule_id = risk["규칙"]

        for pbc in PBC_CATALOG[rule_id]:
            results.append({
                "기업": risk["기업"],
                "규칙": rule_id,
                "검토 신호": risk["검토 신호"],
                "관련 기준": risk["관련 기준"],
                **pbc
            })

    return pd.DataFrame(results, columns=PBC_COLUMNS)
